'use strict';
const fs = require('fs');
const path = require('path');
const paths = require('./paths');
const manifest = require('./manifest');
const { removeManagedFile, orderManagedFiles } = require('./uninstall');
const { updateInstalledSkill } = require('./skill');
const pkg = require('../package.json');

// The package ships ONE prebuilt multicall Rust exe; every tool
// is just a name it is invoked as, so the extra .exe files are hardlinks (and
// the extensionless names are shims) of the same binary.
const TOOL_NAMES = ['idle','belownormal','abovenormal','high','realtime','capc','capt','capm','caps','capn','cy','cx','admin','uiup'];
const EXE_NAME = 'wnice.exe';
const SIDECAR_NAME = 'wnice.exe.managed';

// What 0.2.x installed (PowerShell launchers + prebuilt DLLs). Recognized only
// so an upgrade or uninstall can remove them; ownership still needs the
// `win-nice: managed-file` marker (in the file, or in a DLL's .managed sidecar).
const LEGACY_DLL_NAMES = [
  'AboveNormal', 'Admin', 'BelowNormal', 'Capc', 'Capm', 'Capn', 'Caps', 'Capt',
  'Cx', 'Cy', 'High', 'Idle', 'Realtime',
].map((n) => `${n}Launcher.dll`).concat('EnvironmentNotifier.dll');
const LEGACY_NAMES = new Set([
  ...TOOL_NAMES.flatMap((t) => [`${t}.ps1`, `${t}.bat`]),
  'load-launcher.ps1',
  ...LEGACY_DLL_NAMES.flatMap((d) => [d, `${d}.managed`]),
]);

// Injectable so tests can point at a fake exe without a Rust build.
function sourceBinDir() {
  return process.env.WIN_NICE_SOURCE_BIN || path.join(__dirname, '..', 'bin');
}

// The 31 names a complete install consists of: the real exe, its sidecar
// marker, one hardlinked .exe per tool, and one extensionless Git Bash shim
// per tool plus the `wnice` frontend itself.
function expectedInstalledFiles() {
  return [
    EXE_NAME,
    SIDECAR_NAME,
    ...TOOL_NAMES.map((t) => `${t}.exe`),
    ...TOOL_NAMES.map((t) => t),
    EXE_NAME.replace(/\.exe$/, ''),
  ];
}

// Extensionless shims for Git Bash (which ignores PATHEXT on bare names):
// they just exec the sibling .exe. MSYS2_ARG_CONV_EXCL='*' must be set BEFORE
// the export so POSIX-style arg rewriting doesn't mangle Windows-looking args.
function shimText(name) {
  return [
    '#!/bin/sh',
    '# win-nice: managed-file (generated by the win-nice installer)',
    `MSYS2_ARG_CONV_EXCL='*'`,
    'export MSYS2_ARG_CONV_EXCL',
    `exec "$(dirname "$0")/${name}.exe" "$@"`,
    '',
  ].join('\n');
}

// A file counts as ours (safe to delete/replace) iff: the installer's sidecar
// marks the exe set, the exe bytes match the shipped source exe, the shim
// text matches what we generate, or it's the sidecar itself. Anything else
// (a foreign capc.exe, a renamed script) is never touched.
function isOwnedArtifact(filePath, dir) {
  const name = path.basename(filePath);
  const exeNames = new Set([EXE_NAME, ...TOOL_NAMES.map((t) => `${t}.exe`)]);
  const shimNames = new Set([EXE_NAME.replace(/\.exe$/, ''), ...TOOL_NAMES]);
  try {
    if (name === SIDECAR_NAME) {
      return fs.readFileSync(filePath, 'utf8').includes(manifest.MARKER);
    }
    if (exeNames.has(name)) {
      const sidecar = path.join(dir, SIDECAR_NAME);
      try {
        if (fs.readFileSync(sidecar, 'utf8').includes(manifest.MARKER)) return true;
      } catch {}
      const source = path.join(sourceBinDir(), EXE_NAME);
      return fs.readFileSync(filePath).equals(fs.readFileSync(source));
    }
    if (shimNames.has(name)) {
      // Older versions' shims had other text but the same marker comment.
      const text = fs.readFileSync(filePath, 'utf8');
      return text === shimText(name) || text.includes(manifest.MARKER);
    }
    if (LEGACY_NAMES.has(name)) {
      return manifest.hasMarker(filePath);
    }
  } catch {}
  return false;
}

// `npm install -g win-nice@newer` only runs postinstall (this function) - unlike
// `win-nice reinstall`, which does uninstall()+install(), it never diffs against
// what a previous version left behind. Without this, a tool dropped in a newer
// version stays orphaned in binDir forever. Safe to call before the target dir
// even exists (read() returns null, staleNames is empty).
function cleanupStaleFiles(dir, currentFiles) {
  const currentSet = new Set(currentFiles);
  const previous = manifest.read(paths.manifestPath());
  if (previous && Array.isArray(previous.files)) {
    const staleNames = orderManagedFiles(previous.files.filter((name) => !currentSet.has(name)));
    const previousDir = previous.binDir || dir;
    for (const name of staleNames) {
      removeManagedFile(path.join(previousDir, name), dir, { requireOwnership: false });
    }
    return;
  }

  // Manifest missing/corrupt (deleted by hand, or predates this file's
  // existence) - same recovery uninstall() already relies on for the same
  // situation: scan the known install dir directly and remove only entries
  // that (a) aren't part of the CURRENT tool set and (b) are recognizably
  // ours (see isOwnedArtifact). Anything the user dropped there themselves
  // is never touched.
  if (!fs.existsSync(dir)) return;
  for (const name of orderManagedFiles(fs.readdirSync(dir))) {
    if (currentSet.has(name)) continue;
    removeManagedFile(path.join(dir, name), dir, { requireOwnership: true });
  }
}

// On Windows a RUNNING .exe cannot be overwritten or deleted, but it CAN be
// renamed. `npm i -g win-nice@newer` while users' long-lived tools run would
// otherwise fail halfway - so Phase R renames every existing exe target aside
// before Phase C recreates it.
function renameAside(target) {
  if (!fs.existsSync(target)) return null;
  for (let n = 1; ; n++) {
    const aside = `${target}.old-${n}`;
    if (!fs.existsSync(aside)) {
      fs.renameSync(target, aside);
      return aside;
    }
  }
}

// Strict pattern per known tool ONLY (never a loose glob): a leftover is a
// name install()/uninstall() created via renameAside. evil.exe.old-3 or
// capm.exe.old-x must NOT match.
function isOldLeftoverName(name) {
  const names = new Set([EXE_NAME, ...TOOL_NAMES.map((t) => `${t}.exe`)]);
  for (const n of names) {
    const m = new RegExp(`^${n.replace(/[.]/g, '\\$&')}\\.old-(\\d+)$`).exec(name);
    if (m) return true;
  }
  return false;
}

function install({ updatePath = true, _fs = fs } = {}) {
  if (!process.env.WIN_NICE_HOME && paths.isSourceCheckout()) {
    console.log(
      'Running from a source checkout - skipping real install. ' +
        'Set WIN_NICE_HOME to force a target directory, or install the published package.'
    );
    return null;
  }

  const dir = paths.binDir();
  fs.mkdirSync(dir, { recursive: true });

  const files = expectedInstalledFiles();
  cleanupStaleFiles(dir, files);

  const source = path.join(sourceBinDir(), EXE_NAME);
  const targetExe = path.join(dir, EXE_NAME);

  // Check ALL foreign targets FIRST, before creating anything: writing the
  // sidecar before these checks would make isOwnedArtifact treat a pre-existing
  // foreign file as ours (sidecar present => owned) and silently overwrite it.
  const targetShimNames = [...TOOL_NAMES, EXE_NAME.replace(/\.exe$/, '')];
  const allTargets = [targetExe, ...TOOL_NAMES.map((t) => path.join(dir, `${t}.exe`)), ...targetShimNames.map((n) => path.join(dir, n))];
  // A name the previous install's manifest lists in this same directory was
  // put there by us, whatever its current bytes (an older version's layout).
  const previous = manifest.read(paths.manifestPath());
  const previouslyInstalled = new Set(
    previous && Array.isArray(previous.files) && path.resolve(previous.binDir || dir) === path.resolve(dir)
      ? previous.files
      : []
  );
  for (const target of allTargets) {
    if (fs.existsSync(target) && !previouslyInstalled.has(path.basename(target)) && !isOwnedArtifact(target, dir)) {
      throw new Error(`refusing to overwrite a pre-existing unrelated file: ${target}`);
    }
  }

  // Snapshots FIRST, before Phase R: a read error then aborts with nothing
  // touched. prevBytes holds the pre-upgrade bytes of every existing non-exe
  // contract name (sidecar + shims); exes are restored by rename-back instead.
  // ENOENT (TOCTOU) = "did not exist"; any other read error is fatal.
  const exeTargets = [targetExe, ...TOOL_NAMES.map((t) => path.join(dir, `${t}.exe`))];
  const exeSet = new Set(exeTargets);
  const snapshot = (target) => {
    try {
      return fs.readFileSync(target);
    } catch (err) {
      if (err && err.code === 'ENOENT') return null;
      throw new Error(
        `could not back up ${target} (${err && err.code}) - close running win-nice tools and retry`
      );
    }
  };
  const prevBytes = new Map();
  for (const name of files) {
    const target = path.join(dir, name);
    if (exeSet.has(target) || !fs.existsSync(target)) continue;
    const bytes = snapshot(target);
    if (bytes !== null) prevBytes.set(target, bytes);
  }
  // Previous manifest: restored exactly on failure, deleted if there was none.
  const manifestPath = paths.manifestPath();
  const prevManifestBytes = fs.existsSync(manifestPath) ? snapshot(manifestPath) : null;

  // Phase R: rename every existing .exe target aside (renaming a RUNNING exe
  // IS allowed on Windows; overwriting/deleting is not). Any non-ENOENT error
  // renames every already-moved-aside file back (best-effort) and aborts.
  const renamedAside = [];
  for (const target of exeTargets) {
    try {
      const aside = renameAside(target);
      if (aside) renamedAside.push({ from: target, to: aside });
    } catch (err) {
      if (err && err.code !== 'ENOENT') {
        for (const { from, to } of renamedAside) {
          try { fs.renameSync(to, from); } catch {}
        }
        throw new Error(
          `could not set aside ${target} (${err.code}) - close running win-nice tools and retry`
        );
      }
    }
  }
  const renamedFroms = new Set(renamedAside.map(({ from }) => from));

  // Phase C + manifest write are ONE transaction (rollback below). _fs is a
  // test seam: tests inject failing ops to simulate a locked exe (real image
  // locks can't be simulated with Node handles - FILE_SHARE_DELETE). Phase R
  // always uses the real fs (renames must actually work).
  const created = new Set();
  const overwritten = new Set();
  const track = (target) => {
    if (renamedFroms.has(target)) return; // restored via rename-back
    (prevBytes.has(target) ? overwritten : created).add(target);
  };

  // Every destination is REGISTERED via track() BEFORE the write/copy/link,
  // so even a partial write followed by a throw is rolled back (created ->
  // deleted, overwritten -> byte-restored). A created path Phase C never got
  // to write is simply missing at rollback; unlinkSync's ENOENT is swallowed.
  try {
    track(targetExe);
    _fs.copyFileSync(source, targetExe);
    track(path.join(dir, SIDECAR_NAME));
    _fs.writeFileSync(path.join(dir, SIDECAR_NAME), `${manifest.MARKER}\n`);

    // Hardlinks save ~6MB x14 vs full copies; fall back to a copy on any
    // error (filesystems/devices that don't support them).
    for (const t of TOOL_NAMES) {
      const target = path.join(dir, `${t}.exe`);
      track(target);
      if (_fs.existsSync(target)) _fs.unlinkSync(target);
      try {
        _fs.linkSync(source, target);
      } catch {
        _fs.copyFileSync(source, target);
      }
    }

    for (const name of targetShimNames) {
      const target = path.join(dir, name);
      track(target);
      if (_fs.existsSync(target)) _fs.unlinkSync(target);
      _fs.writeFileSync(target, shimText(name));
    }

    manifest.write(manifestPath, {
      version: pkg.version,
      installedAt: new Date().toISOString(),
      binDir: dir,
      files,
    });
  } catch (err) {
    // Rollback (all best-effort), then rethrow:
    // 1. rename every renamed-aside exe back to its original name;
    // 2. restore the pre-upgrade bytes of every overwritten sidecar/shim;
    // 3. delete only the files Phase C actually created fresh;
    // 4. restore the previous manifest bytes (or delete it if there was none).
    for (const { from, to } of renamedAside) {
      try { fs.renameSync(to, from); } catch {}
    }
    for (const [target, bytes] of prevBytes) {
      if (renamedFroms.has(target)) continue;
      try { fs.writeFileSync(target, bytes); } catch {}
    }
    for (const p of created) {
      try { fs.unlinkSync(p); } catch {}
    }
    if (prevManifestBytes !== null) {
      try { fs.writeFileSync(manifestPath, prevManifestBytes); } catch {}
    } else {
      try { fs.unlinkSync(manifestPath); } catch {}
    }
    throw new Error(`${err.message} - close running win-nice tools and retry`);
  }

  // Transaction committed (manifest written): best-effort cleanup of stale
  // .old-N leftovers (ours from this run's Phase R, plus older upgrades). A
  // still-running old exe can only be removed later.
  for (const entry of fs.readdirSync(dir)) {
    if (isOldLeftoverName(entry)) {
      try { fs.unlinkSync(path.join(dir, entry)); } catch {}
    }
  }

  if (updatePath) {
    const current = paths.readUserPath();
    const next = paths.addToPathString(current, dir);
    if (next !== current) {
      paths.writeUserPath(next);
      console.log(`Added ${dir} to your PATH. Restart your terminal for it to take effect.`);
    }
  }

  console.log(`win-nice ${pkg.version} installed: 30 files (wnice.exe + 14 tool links + 15 shims) + sidecar -> ${dir}`);

  // Only touches a skill copy that's already there and still ours (opt-in
  // stays opt-in) - see updateInstalledSkill's own comment for why this needs
  // to run on every install(), not just the explicit `win-nice skill install`.
  for (const r of updateInstalledSkill()) {
    if (r.updated) console.log(`updated skill: ${r.file}`);
  }

  return { dir, files };
}

module.exports = {
  install,
  isSourceCheckout: paths.isSourceCheckout,
  TOOL_NAMES,
  EXE_NAME,
  SIDECAR_NAME,
  sourceBinDir,
  expectedInstalledFiles,
  shimText,
  isOwnedArtifact,
  renameAside,
  isOldLeftoverName,
};
